def validate_args(args: argparse.Namespace) -> None:
    if args.mode == "metric":
        if not args.metric:
            print("Error: --metric is required when --mode is metric.", file=sys.stderr)
            sys.exit(1)
        if not args.direction:
            print("Error: --direction is required when --mode is metric.", file=sys.stderr)
            sys.exit(1)
        normalized_target = args.target.strip().lower() if args.target else ""
        if not normalized_target or normalized_target in {"tbd", "todo", "unknown"}:
            print("Error: --target is required when --mode is metric.", file=sys.stderr)
            sys.exit(1)
    elif args.mode == "qualitative":
        if not args.criteria:
            print("Error: --criteria is required when --mode is qualitative.", file=sys.stderr)
            sys.exit(1)

    if args.researchers < 1:
        fail("INVALID_BUDGET", "--researchers must be >= 1")

    if args.researchers > 26:
        fail("INVALID_BUDGET", "--researchers must be <= 26")

    if args.iterations_per_round < 1:
        fail("INVALID_BUDGET", "--iterations-per-round must be >= 1")

    if args.max_rounds < 1:
        fail("INVALID_BUDGET", "--max-rounds must be >= 1")

    if args.noise_runs < 1:
        fail("INVALID_BUDGET", "--noise-runs must be >= 1")

    if not math.isfinite(args.min_delta) or args.min_delta < 0:
        fail("INVALID_BUDGET", "--min-delta must be finite and >= 0")


def scaffold(args: argparse.Namespace) -> None:
    date = datetime.now().strftime("%Y-%m-%d")
    title = goal_to_title(args.goal)
    output = Path(args.output)
    rids = researcher_ids(args.researchers)
    max_total_iterations = args.researchers * args.iterations_per_round * args.max_rounds
    researcher_sections = make_researcher_sections(rids, args.strategy)
    guard_text = args.guard if args.guard else "_No guard constraint. Leave blank or define a safety invariant._"
    noise_runs = args.noise_runs
    min_delta = args.min_delta
    if args.devils_advocate == "yes":
        critic_setting = "enabled"
    elif args.devils_advocate == "no":
        critic_setting = "disabled"
    else:
        critic_setting = "ask user before run"

    fd, output = open_safe_directory(output)
    try:
        entries = os.listdir(fd)
        if entries and not args.force:
            fail(
                "OUTPUT_NOT_EMPTY",
                f"output directory '{output}' already exists and is not empty. Use --force to overwrite.",
            )
        reject_unsafe_leaf(fd, "workspace", directory=True)
        managed = list(STATIC_MANAGED_FILE_LEAVES)
        managed.extend(entry for entry in entries if RESEARCHER_LEAF.fullmatch(entry))
        for leaf in managed:
            reject_unsafe_leaf(fd, leaf)
        if args.force:
            for leaf in managed:
                remove_regular_leaf(fd, output, leaf)
        if leaf_info(fd, "workspace") is None:
            verify_directory_identity(output, fd)
            os.mkdir("workspace", 0o755, dir_fd=fd)

        if args.mode == "metric":
            gate_success_definition = f"metric {args.metric} ({args.direction}) target {args.target}"
            conf_text = CONFERENCE_TEMPLATE_METRIC.format(
                title=title,
                goal=args.goal,
                metric=args.metric,
                target=args.target,
                direction=args.direction,
                researchers=args.researchers,
                iterations_per_round=args.iterations_per_round,
                max_rounds=args.max_rounds,
                strategy=args.strategy,
                researcher_sections=researcher_sections,
                max_total_iterations=max_total_iterations,
                guard=guard_text,
                noise_runs=noise_runs,
                min_delta=min_delta,
                gate_success_definition=gate_success_definition,
                critic_setting=critic_setting,
            )
        else:
            gate_success_definition = f"criteria: {args.criteria}"
            conf_text = CONFERENCE_TEMPLATE_QUALITATIVE.format(
                title=title,
                goal=args.goal,
                criteria=args.criteria,
                researchers=args.researchers,
                iterations_per_round=args.iterations_per_round,
                max_rounds=args.max_rounds,
                strategy=args.strategy,
                researcher_sections=researcher_sections,
                max_total_iterations=max_total_iterations,
                guard=guard_text,
                noise_runs=noise_runs,
                min_delta=min_delta,
                gate_success_definition=gate_success_definition,
                critic_setting=critic_setting,
            )
        write_new_leaf(fd, output, "conference.md", conf_text)

        for rid in rids:
            log = LOG_TEMPLATE.format(rid=rid, date=date, goal=args.goal)
            write_new_leaf(fd, output, f"researcher_{rid}_log.md", log)
            tsv = RESEARCHER_TSV_HEADER + RESEARCHER_TSV_BASELINE.format(date=date)
            write_new_leaf(fd, output, f"researcher_{rid}_results.tsv", tsv)

        write_new_leaf(fd, output, "conference_results.tsv", CONFERENCE_TSV_HEADER)
        write_new_leaf(fd, output, "conference_events.jsonl", "")
        verify_directory_identity(output, fd)
    finally:
        os.close(fd)

    # Print success
    print(f"\nConference project scaffolded at: {output.resolve()}")
    print(f"\nFiles created:")
    print(f"  conference.md")
    for rid in rids:
        print(f"  researcher_{rid}_log.md")
        print(f"  researcher_{rid}_results.tsv")
    print(f"  conference_results.tsv")
    print(f"  conference_events.jsonl")
    print(f"  workspace/")
    print(f"\nPre-flight gate:")
    print(f"  Researcher count: {args.researchers}")
    print(f"  Max total iterations: {max_total_iterations}")
    print(f"  Success definition: {gate_success_definition}")
    print(f"  Critic / Devil's Advocate: {critic_setting}")
    print("  Final confirmation: pending before Phase 1")
    print(f"\nNext steps:")
    print(f"  1. Open conference.md and fill in 'Current Approach' and 'Search Space'.")
    print(f"  2. Edit researcher focus areas if using 'assigned' strategy.")
    print("  3. Select $litcodex:autoconference and provide the generated conference.md path.")
    print("  4. Approve the plan, then select $litcodex:start-work for the root-owned conference.")


def main() -> None:
    args = parse_args()
    validate_args(args)
    preflight_capabilities()
    scaffold(args)


if __name__ == "__main__":
    main()
